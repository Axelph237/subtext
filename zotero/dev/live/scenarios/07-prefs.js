resetPrefs();
Zotero.Utilities.Internal.openPreferences('subtext-prefpane');
let prefWin = null;
check(await until(() => (prefWin = Services.wm.getMostRecentWindow('zotero:pref')) && prefWin.document.getElementById('subtext-test'), 15000), 'SubTeXt pane loads in Settings');
const $ = (id) => prefWin.document.getElementById(id);
prefWin.resizeTo(900, 820);
const detected = await Zotero.SubTeXt.detectClaudePath();
check(await until(() => $('subtext-claude-path').placeholder === detected, 5000), 'CLI path placeholder is the detected path', [$('subtext-claude-path').placeholder, detected]);
const radios = [...$('subtext-backend').querySelectorAll('radio')].map((r) => [r.value, r.label]);
check(JSON.stringify(radios) === JSON.stringify(Object.entries(Zotero.SubTeXt.core.BACKENDS).map(([id, b]) => [id, b.label])), 'one radio per registered backend', radios);
check($('subtext-backend').value === 'claude-code', 'Claude Code is selected by default', $('subtext-backend').value);
const items = [...$('subtext-model').menupopup.children].map((m) => m.value);
check(items.length === 4 && items[0] === 'claude-haiku-5-5', 'model list has the three models and Other', items);
check($('subtext-model').value === 'claude-haiku-5-5', 'Haiku is selected by default');
const context = $('subtext-context-chars');
check(context.value === '2000', 'the context field shows the default 2000', context.value);
context.value = '300';
context.dispatchEvent(new prefWin.Event('input'));
check(Zotero.Prefs.get(PREF + 'contextChars', true) === 300, 'a context size is saved as a number', Zotero.Prefs.get(PREF + 'contextChars', true));
check(Services.prefs.getPrefType(PREF + 'contextChars') === Services.prefs.PREF_INT, 'the context pref stays an int pref');
context.value = '';
context.dispatchEvent(new prefWin.Event('input'));
check(Zotero.Prefs.get(PREF + 'contextChars', true) === 2000, 'an empty context field saves the default');
const shown = (backend) => !prefWin.document.querySelector(`[data-backend="${backend}"]`).hidden;
check(shown('claude-code') && !shown('anthropic'), 'only Claude Code settings show for the Claude Code backend');

$('subtext-test').doCommand();
check(await until(() => /\\int/.test($('subtext-test-result').textContent), 30000), 'Test button shows converted LaTeX', $('subtext-test-result').textContent);
const result = $('subtext-test-result').textContent;
const testShot = await snap('07-prefs-test', prefWin);

$('subtext-backend').selectedItem = $('subtext-backend').querySelector('radio[value="anthropic"]');
$('subtext-backend').dispatchEvent(new prefWin.Event('command'));
check(Zotero.Prefs.get(PREF + 'backend', true) === 'anthropic', 'choosing API key saves the backend pref');
check(shown('anthropic') && !shown('claude-code'), 'API key settings show for the API key backend');
$('subtext-api-key').value = '';
$('subtext-test').doCommand();
check(await until(() => /Error: No Anthropic API key/.test($('subtext-test-result').textContent), 5000), 'Test with no key shows the error', $('subtext-test-result').textContent);
const errorShot = await snap('07-prefs-error', prefWin);

$('subtext-api-key').value = 'sk-ant-not-a-real-key';
$('subtext-api-key').dispatchEvent(new prefWin.Event('change'));
await wait(300);
check(Zotero.SubTeXt.getApiKey() === 'sk-ant-not-a-real-key', 'API key is stored in the login manager');
check(!Services.prefs.getBranch('extensions.subtext.').getChildList('').some((name) => String(Zotero.Prefs.get(PREF + name, true)).includes('sk-ant')), 'API key is not written to prefs');
$('subtext-test').doCommand();
check(await until(() => /^Error: /.test($('subtext-test-result').textContent) && !/No Anthropic API key/.test($('subtext-test-result').textContent), 20000), 'Test with a bad key shows the API error', $('subtext-test-result').textContent);
const apiError = $('subtext-test-result').textContent;

$('subtext-model').value = '__other__';
$('subtext-model').dispatchEvent(new prefWin.Event('command'));
check(!$('subtext-model-custom').hidden, 'Other reveals the model id field');
$('subtext-model-custom').value = 'claude-sonnet-5-5';
$('subtext-model-custom').dispatchEvent(new prefWin.Event('input'));
check(Zotero.Prefs.get(PREF + 'model', true) === 'claude-sonnet-5-5', 'free-text model id is saved');

await Zotero.SubTeXt.setApiKey('');
prefWin.close();
resetPrefs();
return { fails, result, apiError, testShot, errorShot };
